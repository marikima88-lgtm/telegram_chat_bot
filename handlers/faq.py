@router.callback_query(F.data == "faq")
async def show_faq(callback: CallbackQuery) -> None:
    await callback.message.edit_text("Если у вас есть вопрос, напишите его простыми словами, и я постараюсь подсказать.", reply_markup=get_main_menu_keyboard())


@router.message()
async def handle_text(message: Message) -> None:
    text = message.text.lower() if message.text else ""
    if not text:
        return
    user = await get_user(message.from_user.id)
    branch_name = get_branch_display(user.get("branch_id") if user else None)
    for keyword, answer in FAQ_RESPONSES.items():
        if keyword in text:
            if keyword in {"адрес", "график", "работаете"}:
                await message.answer(f"{answer}\n\nТекущий филиал: {branch_name}")
            else:
                await message.answer(answer)
            return
    await message.answer("Я пока не смог точно определить ваш вопрос. Выберите нужный раздел в меню или оставьте заявку сотруднику Ecash.")
