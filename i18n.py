# Названия городов на казахском, если отличаются от русских.
CITY_NAMES: dict[str, dict[str, str]] = {
    "kk": {"aktobe": "Ақтөбе"},
}


def normalize_language(lang: str | None) -> str:
    return lang if lang in LANGUAGES else DEFAULT_LANGUAGE


def t(key: str, lang: str | None = DEFAULT_LANGUAGE, **kwargs: object) -> str:
    variants = TEXTS[key]
    text = variants.get(normalize_language(lang)) or variants[DEFAULT_LANGUAGE]
    return text.format(**kwargs) if kwargs else text


def localize_city(city_id: str, default_name: str, lang: str | None = DEFAULT_LANGUAGE) -> str:
    return CITY_NAMES.get(normalize_language(lang), {}).get(city_id, default_name)
